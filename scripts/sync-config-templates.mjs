#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sources = {
  core: 'config-templates/config.example.jsonc',
  mcp: 'config-templates/integrations/mcp.example.jsonc',
  a2a: 'config-templates/integrations/a2a.example.jsonc',
  extensions: 'config-templates/integrations/extensions.example.jsonc',
};

const contents = Object.fromEntries(await Promise.all(
  Object.entries(sources).map(async ([name, relativePath]) => [
    name,
    await readFile(path.join(root, relativePath), 'utf8'),
  ]),
));

const generated = `/* Generated by scripts/sync-config-templates.mjs. Do not edit. */\n`
  + `export const CONFIG_TEMPLATES = ${JSON.stringify(contents, null, 2)} as const;\n`
  + `export type ConfigTemplateName = keyof typeof CONFIG_TEMPLATES;\n`
  + `export function getConfigTemplate(name: ConfigTemplateName): string {\n`
  + `  return CONFIG_TEMPLATES[name];\n}\n`;

const outputs = [
  [path.join(root, 'config.example.jsonc'), contents.core],
  [path.join(root, 'packages/repl/src/common/generated-config-templates.ts'), generated],
];
const check = process.argv.includes('--check');
let drift = false;
for (const [file, expected] of outputs) {
  let current = '';
  try {
    current = await readFile(file, 'utf8');
  } catch {
    // Missing generated output is drift in check mode and created otherwise.
  }
  if (current === expected) continue;
  drift = true;
  if (!check) await writeFile(file, expected, 'utf8');
  else process.stderr.write(`[config-templates] drift: ${path.relative(root, file)}\n`);
}
if (check && drift) process.exitCode = 1;
